// Offline generator: frozen public-store catalog, never a database export.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { validateProduct } from './catalog-source.mjs';

const source = new URL('../supabase/catalog/20260928-public-store.json', import.meta.url);
const target = new URL('../supabase/migrations/20260928162850_restore_historical_public_catalog.sql', import.meta.url);
const raw = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const products = JSON.parse(raw);
if (products.length !== 106 || products.reduce((n, p) => n + p.variantes.length, 0) !== 217)
  throw Error('Historical snapshot must contain 106 products and 217 variants.');
for (const product of products) {
  validateProduct(product);
  for (const image of product.imagenes) {
    if (!/^[a-f0-9]{64}$/.test(image.sha256) || !Number.isSafeInteger(image.bytes) || image.bytes <= 0
      || image.storage_path !== `products/assets/${image.sha256}.${({ 'image/webp': 'webp', 'image/jpeg': 'jpg', 'image/png': 'png', 'image/gif': 'gif', 'image/avif': 'avif' })[image.mime_type]}`)
      throw Error('Invalid public image metadata.');
  }
}
const json = JSON.stringify(products);
if (json.includes('$catalog_snapshot$')) throw Error('SQL delimiter collision.');
const sql = `-- GENERATED by scripts/build-historical-catalog.mjs; do not edit.\n-- Public storefront snapshot, 2026-09-28; no production database rows.\n-- Source SHA256: ${createHash('sha256').update(raw).digest('hex')}\n-- Historical replay bridge: later reconciliations require these exact variants.\n-- Images are metadata only; Storage binaries are not imported.\nbegin;\ndo $restore$\ndeclare item jsonb;\nbegin\n for item in select value from jsonb_array_elements($catalog_snapshot$${json}$catalog_snapshot$::jsonb) loop\n  perform public.mb_importar_catalogo(item);\n end loop;\nend $restore$;\ncommit;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== sql) throw Error('Regenerate the historical catalog migration.');
} else writeFileSync(target, sql);
console.log(`Historical catalog verified: ${products.length} products, 217 variants (${fileURLToPath(source)}).`);
